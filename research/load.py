def read_long(path: str) -> pd.DataFrame:
    """Возвращает long-таблицу: exporter (столбец), importer (строка), product, unit, value."""
    raw = pd.read_excel(path, header=None)
    prod = raw.iloc[3].ffill()
    exporter = raw.iloc[4].astype(str).str.strip()
    body = raw.iloc[5:].copy()
    importer = body.iloc[:, 0].astype(str).str.strip()
    recs = []
    for j in range(1, raw.shape[1]):
        col = pd.to_numeric(body.iloc[:, j], errors="coerce")
        p = str(prod.iloc[j]).replace("\xa0", " ").strip()
        name, _, unit = p.rpartition(",")
        for imp, v in zip(importer, col):
            if pd.notna(v) and v != 0:
                recs.append((exporter.iloc[j], imp, name.strip(), unit.strip(), float(v)))
    return pd.DataFrame(recs, columns=["exporter", "importer", "product", "unit", "value"])


def is_aggregate(name: str) -> bool:
    n = name.lower()
    return FD in n or n in DROP_EXACT


def clean(df: pd.DataFrame) -> pd.DataFrame:
    """Корректная очистка: 85 субъектов без двойного счёта, без петель."""
    m = ~df["exporter"].map(is_aggregate) & ~df["importer"].map(is_aggregate)
    df = df[m & (df["exporter"] != df["importer"])].copy()
    df["exporter"] = df["exporter"].replace(SHORT)
    df["importer"] = df["importer"].replace(SHORT)
    return df
